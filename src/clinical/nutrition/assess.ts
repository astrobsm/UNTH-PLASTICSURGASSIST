/**
 * One call that turns whatever is known about a patient into a complete,
 * traceable nutrition assessment: anthropometry → screening → requirements →
 * targets. Missing inputs never throw; they lower what can be said and are
 * listed as warnings.
 */
import { NUTRITION_CONFIG } from './config';
import type { NutritionConfig } from './config/nutrition.v1';
import { adjustedBwOf, bmiCalc, gripOf, heightOf, ibwOf, lossPct3to6m, mamcOf, muacBmiBand, weightChanges, weightOf } from './anthropometry';
import { glimOf, mustOf, nrs2002Of, nutricOf, sgaOf } from './screening';
import {
  catabolicReasons, energyOptions, fluidOf, goalPlan, micronutrientPriorities, OUT_OF_SCOPE_NOTICE, proteinOf, recommendedEnergy, refeedingOf, scopeOf,
  type Body, type EnergyOption, type GoalPlan,
} from './requirements';
import type { ScheduleLevel } from './monitoring';
import type { NutritionInputs } from './types';

export const DECISION_SUPPORT_NOTICE = 'Generated by decision-support software. Review before clinical use.';

export interface Targets {
  kcal: number | null;
  proteinG: number | null;
  fluidMl: number | null;
  carbG: number | null;
  fatG: number | null;
  restrictions: string[];
}

export function assessNutrition(inputs: NutritionInputs, cfg: NutritionConfig = NUTRITION_CONFIG, now = new Date()) {
  const i = inputs;
  const warnings: string[] = [];
  const scope = scopeOf(i);

  const height = heightOf(i, cfg);
  const weight = weightOf(i, cfg);
  if (!height) warnings.push('No height — measure, or record knee height or ulna length');
  if (!weight) warnings.push('No weight — weigh (bed scale/hoist), or record knee height + MUAC for an estimate');
  const bmi = bmiCalc(weight?.wholeBodyKg ?? null, height?.value ?? null);
  const muacBand = bmi ? null : muacBmiBand(i, cfg);
  const ibw = ibwOf(height?.value ?? null, i.sex, cfg);
  const adjbw = bmi && bmi.value >= cfg.obeseBmi.value ? adjustedBwOf(weight?.wholeBodyKg ?? null, ibw?.value ?? null, cfg) : null;
  const loss = lossPct3to6m(i);
  const changes = weightChanges(i.weightHistory, now);

  const anthro = { bmi: bmi?.value ?? null, muacBand: muacBand?.value ?? null, lossPct: loss?.value ?? null };
  const screening = {
    must: mustOf(i, anthro, cfg),
    nrs2002: nrs2002Of(i, anthro, cfg),
    sga: sgaOf(i),
    glim: glimOf(i, anthro, cfg),
    nutric: nutricOf(i, cfg),
  };

  const body: Body = { kg: weight?.value ?? null, heightCm: height?.value ?? null, bmi: bmi?.value ?? null, ibw: ibw?.value ?? null, adjbw: adjbw?.value ?? null };
  const catabolic = catabolicReasons(i, cfg);

  const options = energyOptions(i, body, cfg);
  const recommended = recommendedEnergy(options, i);
  const selected: EnergyOption | null = (i.energyMethod && options.find(o => o.id === i.energyMethod)) || recommended;
  if (i.energyMethod && selected?.id !== i.energyMethod) warnings.push(`Chosen energy method "${i.energyMethod}" cannot be calculated from the data — ${recommended?.label ?? 'none'} used`);
  if (selected?.id === 'mifflin') warnings.push('Resting energy selected — this excludes activity and stress');

  const goal: GoalPlan | null = selected ? goalPlan(i, selected.value, body, cfg) : null;
  const protein = proteinOf(i, body, cfg);
  const refeeding = refeedingOf(i, body, loss?.value ?? null, goal?.targetKcal ?? null, cfg);
  const fluid = fluidOf(i, body, cfg);
  const micronutrients = micronutrientPriorities(i);

  const restrictions: string[] = [];
  if (i.diabetes) restrictions.push(`Carbohydrate control (≤ ${cfg.diabetesCarbMaxPct.value}% of energy), low glycaemic index, spread across meals`);
  if (i.heartFailure || i.ckd) restrictions.push(`Sodium < ${cfg.sodiumRestrictedMg.value / 1000} g/day`);
  if (i.ckd) restrictions.push('Potassium and phosphate limits — physician to set');
  for (const r of i.dietary?.allergies || []) restrictions.push(`Allergy/intolerance: ${r}`);
  for (const r of i.dietary?.religious || []) restrictions.push(`Religious/cultural: ${r}`);
  if (i.dietary?.texture && i.dietary.texture !== 'normal') restrictions.push(`Texture: ${i.dietary.texture.replace(/_/g, ' ')}`);

  let kcal = goal?.targetKcal ?? null;
  const proteinG = protein?.value ?? null;
  let carbG: number | null = null, fatG: number | null = null;
  if (kcal && proteinG) {
    const split = cfg.macroSplit.value;
    const carbPct = i.diabetes ? Math.min(split.carbPct, cfg.diabetesCarbMaxPct.value) : split.carbPct;
    const pKcal = proteinG * 4;
    carbG = Math.round((kcal * carbPct) / 100 / 4);
    fatG = Math.max(0, Math.round((kcal - pKcal - carbG * 4) / 9));
  }
  const day1 = refeeding.schedule[0];
  if (day1) warnings.push(`Refeeding risk ${refeeding.risk}: start at ${day1.kcal} kcal (${day1.kcalPerKg} kcal/kg) and step up over ${refeeding.schedule.length} days`);
  if (!scope.inScope) { kcal = null; carbG = null; fatG = null; }

  const level: ScheduleLevel = refeeding.risk !== 'low' ? 'refeeding'
    : (screening.must && screening.must.value >= 2) || screening.glim.value === 'moderate' || screening.glim.value === 'severe' || screening.nrs2002?.atRisk || screening.nutric?.high || catabolic.length ? 'high'
      : screening.must?.value === 1 ? 'medium'
        : screening.must ? 'low' : 'medium';
  if (!screening.must) warnings.push('MUST could not be scored — monitoring set to medium until screened');

  return {
    configVersion: cfg.version,
    configStatus: cfg.status,
    generatedAt: now.toISOString(),
    notice: DECISION_SUPPORT_NOTICE,
    inputs: i,
    scope: { ...scope, notice: scope.inScope ? null : OUT_OF_SCOPE_NOTICE },
    height, weight, bmi, muacBand, ibw, adjbw,
    mamc: mamcOf(i), grip: gripOf(i, cfg), weightChange: changes, lossPct: loss,
    screening,
    level,
    catabolic,
    energy: { options, recommended, selected },
    goal,
    protein,
    refeeding,
    fluid,
    micronutrients,
    targets: { kcal, proteinG: scope.inScope ? proteinG : null, fluidMl: scope.inScope ? fluid?.value ?? null : null, carbG, fatG, restrictions } as Targets,
    warnings,
  };
}

export type NutritionAssessment = ReturnType<typeof assessNutrition>;
