/**
 * Plain-language renderings of a solved meal plan for documents that predate
 * the nutrition module (the discharge summary's 7-day plan).
 */
import type { NutritionAssessment } from './assess';
import type { MealPlan, PlanItem } from './planner';

const itemText = (i: PlanItem) => {
  const qty = i.units ? `${i.units.n} ${i.units.label}${i.units.n > 1 ? 's' : ''}` : i.measure ? `${i.servedG} g (${i.measure.text.replace(/^≈ /, '≈')})` : `${i.servedG} g`;
  return `${i.name} — ${qty}`;
};
const slotText = (items: PlanItem[], slots: string[]) => items.filter(i => slots.includes(i.slot)).map(itemText).join('; ') || '—';

export interface DischargeMealPlan {
  day1: DischargeDay; day2: DischargeDay; day3: DischargeDay; day4: DischargeDay; day5: DischargeDay; day6: DischargeDay; day7: DischargeDay;
  special_considerations: string[];
  foods_to_avoid: string[];
  hydration_goals: string;
}
interface DischargeDay { breakfast: string; mid_morning_snack: string; lunch: string; afternoon_snack: string; dinner: string; notes?: string }

export function toDischargeMealPlan(plan: MealPlan, assessment: NutritionAssessment | null, opts: { approved: boolean; approvedBy?: string | null }): DischargeMealPlan {
  const day = (n: number): DischargeDay => {
    const d = plan.days[n % plan.days.length];
    return {
      breakfast: slotText(d.items, ['breakfast']), mid_morning_snack: slotText(d.items, ['mid_morning']), lunch: slotText(d.items, ['lunch']),
      afternoon_snack: slotText(d.items, ['afternoon', 'evening']), dinner: slotText(d.items, ['dinner']),
      notes: `${d.totals.energy_kcal ?? 0} kcal · ${d.totals.protein_g ?? 0} g protein`,
    };
  };
  const t = assessment?.targets;
  const special = [
    ...(t?.kcal ? [`Daily targets: ${t.kcal} kcal and ${t.proteinG} g protein (${assessment?.energy.selected?.label ?? 'assessed'})`] : []),
    ...(t?.restrictions || []),
    ...(assessment?.goal && assessment.goal.goal !== 'maintain' ? [`Planned ${assessment.goal.goal === 'lose' ? 'weight loss' : 'weight gain'} of about ${assessment.goal.rateKgWk} kg per week`] : []),
    ...plan.suggestions,
    opts.approved ? `Plan approved by ${opts.approvedBy || 'the nutrition team'}` : 'DRAFT — this meal plan has not yet been approved by a dietitian, consultant or senior registrar',
    'Quantities from the FAO/INFOODS West African Food Composition Table (2019). Generated by decision-support software. Review before clinical use.',
  ];
  return {
    day1: day(0), day2: day(1), day3: day(2), day4: day(3), day5: day(4), day6: day(5), day7: day(6),
    special_considerations: special,
    foods_to_avoid: [...(assessment?.inputs?.dietary?.allergies || []).map(a => `${a} (allergy/intolerance)`), ...(assessment?.inputs?.dietary?.religious || [])],
    hydration_goals: t?.fluidMl ? `About ${t.fluidMl} mL of fluid a day (${assessment?.fluid?.low}–${assessment?.fluid?.high} mL)${assessment?.fluid?.flags.length ? ` — ${assessment.fluid.flags.join('; ')}` : ''}` : 'As advised by the clinical team',
  };
}
