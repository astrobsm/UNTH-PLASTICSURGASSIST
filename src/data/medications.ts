// Helper function to get medications by category
export function getMedicationsByCategory(categoryId: string): Medication[] {
  return MEDICATIONS.filter(m => m.category === categoryId);
}

// Helper function to search medications
export function searchMedications(query: string): Medication[] {
  const lowerQuery = query.toLowerCase();
  return MEDICATIONS.filter(m => 
    m.name.toLowerCase().includes(lowerQuery) ||
    m.genericName.toLowerCase().includes(lowerQuery) ||
    m.brandNames?.some(b => b.toLowerCase().includes(lowerQuery)) ||
    m.indications.some(i => i.toLowerCase().includes(lowerQuery))
  );
}

// Helper function to get medication by ID
export function getMedicationById(id: string): Medication | undefined {
  return MEDICATIONS.find(m => m.id === id);
}
