import React, { useState } from 'react';
import { Sparkles, Loader2, X, Copy, RefreshCw, AlertTriangle, ShieldCheck } from 'lucide-react';
import { apiClient } from '../services/apiClient';

export interface UnitSummaryPatient { id: number | string; name: string; hospital_number: string; ward: string; bed: string; care_start_date?: string | null }

interface PatientRef { ref: string; patient_id: string; name: string | null; hospital_number: string | null; ward: string | null; bed: string | null }
interface UnitSummary {
  overview: string;
  by_ward: { ward: string; count: number; summary: string }[];
  priorities: (PatientRef & { concern: string; action: string })[];
  long_stay: (PatientRef & { note: string })[];
  discharge_candidates: (PatientRef & { reason: string })[];
  data_gaps: string[];
}
interface UnitSummaryResponse { summary: UnitSummary; model: string; patient_count: number; generated_at: string }

const where = (p: PatientRef) => [p.ward, p.bed ? `bed ${p.bed}` : ''].filter(Boolean).join(', ');
const who = (p: PatientRef) => `${p.name || p.ref}${p.hospital_number ? ` (${p.hospital_number})` : ''}`;

export function summaryAsText(unitName: string, r: UnitSummaryResponse): string {
  const s = r.summary;
  const lines = [`AI unit summary — ${unitName} — ${new Date(r.generated_at).toLocaleString()}`, '', s.overview, ''];
  if (s.by_ward.length) { lines.push('BY WARD'); s.by_ward.forEach(w => lines.push(`• ${w.ward} (${w.count}): ${w.summary}`)); lines.push(''); }
  if (s.priorities.length) { lines.push('PRIORITIES'); s.priorities.forEach((p, i) => lines.push(`${i + 1}. ${who(p)} — ${where(p)}: ${p.concern} → ${p.action}`)); lines.push(''); }
  if (s.long_stay.length) { lines.push('LONG STAY'); s.long_stay.forEach(p => lines.push(`• ${who(p)} — ${where(p)}: ${p.note}`)); lines.push(''); }
  if (s.discharge_candidates.length) { lines.push('DISCHARGE REVIEW'); s.discharge_candidates.forEach(p => lines.push(`• ${who(p)} — ${where(p)}: ${p.reason}`)); lines.push(''); }
  if (s.data_gaps.length) { lines.push('DOCUMENTATION GAPS'); s.data_gaps.forEach(g => lines.push(`• ${g}`)); lines.push(''); }
  lines.push('Generated by Claude (Anthropic) from de-identified records. Check against the patient before acting.');
  return lines.join('\n');
}

/**
 * "AI summary" for the open unit: Claude reads the unit's admitted patients
 * (identifiers removed on the server) and returns a handover analysis —
 * overview, per-ward summary, priorities, long stays, discharge candidates and
 * documentation gaps.
 */
const UnitAISummary: React.FC<{ unitName: string; patients: UnitSummaryPatient[]; onOpenPatient: (id: string) => void }> = ({ unitName, patients, onOpenPatient }) => {
  const [open, setOpen] = useState(false);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<UnitSummaryResponse | null>(null);
  const [copied, setCopied] = useState(false);

  const generate = async () => {
    setLoading(true); setError(null); setCopied(false);
    try {
      const r = await apiClient.request<UnitSummaryResponse>('/ai/unit-summary', {
        method: 'POST',
        body: JSON.stringify({
          unit_name: unitName,
          patients: patients.map(p => ({ id: p.id, name: p.name, hospital_number: p.hospital_number, ward: p.ward, bed: p.bed, care_start_date: p.care_start_date || null })),
        }),
        timeout: 35000,
      } as any);
      setResult(r);
    } catch (e: any) {
      setError(e?.message || 'Could not generate the summary');
    } finally {
      setLoading(false);
    }
  };

  const start = () => { setOpen(true); if (!result && !loading) generate(); };
  const copy = () => { if (result) navigator.clipboard?.writeText(summaryAsText(unitName, result)).then(() => setCopied(true)).catch(() => {}); };

  const PatientLine: React.FC<{ p: PatientRef; children: React.ReactNode }> = ({ p, children }) => (
    <li className="text-sm">
      <button className="font-medium text-primary-700 hover:underline" onClick={() => onOpenPatient(p.patient_id)}>{who(p)}</button>
      {where(p) && <span className="text-xs text-gray-500"> · {where(p)}</span>}
      <div className="text-gray-700">{children}</div>
    </li>
  );

  const s = result?.summary;
  return (
    <>
      <button
        onClick={start}
        disabled={!patients.length}
        title="Claude reads this unit's admitted patients (identifiers removed) and writes a handover analysis"
        className="px-3 py-1.5 text-xs font-medium rounded-lg bg-violet-600 text-white hover:bg-violet-700 disabled:opacity-50 flex items-center gap-1"
      >
        <Sparkles className="h-3.5 w-3.5" /> AI summary
      </button>
      {open && (
        <div className="fixed inset-0 z-[60] bg-black/40 flex items-end sm:items-center justify-center p-0 sm:p-4" onClick={() => setOpen(false)}>
          <div className="bg-white w-full sm:max-w-3xl rounded-t-xl sm:rounded-xl max-h-[90vh] overflow-y-auto" onClick={e => e.stopPropagation()}>
            <div className="flex items-center justify-between px-4 py-3 border-b sticky top-0 bg-white z-10">
              <h2 className="font-semibold flex items-center gap-2"><Sparkles className="w-5 h-5 text-violet-600" /> AI summary — {unitName}</h2>
              <div className="flex items-center gap-1">
                {result && <button onClick={copy} className="p-1.5 rounded hover:bg-gray-100" title="Copy summary"><Copy className="w-4 h-4" /></button>}
                <button onClick={generate} disabled={loading} className="p-1.5 rounded hover:bg-gray-100 disabled:opacity-50" title="Regenerate"><RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} /></button>
                <button onClick={() => setOpen(false)} aria-label="Close" className="p-1.5 rounded hover:bg-gray-100"><X className="w-5 h-5" /></button>
              </div>
            </div>
            <div className="p-4 space-y-4">
              {copied && <div className="text-xs text-green-700">Copied.</div>}
              {loading && (
                <div className="py-10 text-center text-sm text-gray-500">
                  <Loader2 className="w-6 h-6 animate-spin mx-auto mb-2 text-violet-500" />
                  Claude is reading {patients.length} patient{patients.length === 1 ? '' : 's'}… this can take up to 30 seconds.
                </div>
              )}
              {error && !loading && <div className="bg-red-50 text-red-700 px-3 py-2 rounded text-sm">{error}</div>}
              {s && !loading && (
                <>
                  <p className="text-sm text-gray-800 whitespace-pre-line">{s.overview}</p>
                  {s.priorities.length > 0 && (
                    <section>
                      <h3 className="text-sm font-semibold text-red-700 flex items-center gap-1 mb-1"><AlertTriangle className="w-4 h-4" /> Priorities today</h3>
                      <ol className="space-y-2 list-decimal pl-5">
                        {s.priorities.map(p => <PatientLine key={p.ref} p={p}><span>{p.concern}</span> <span className="text-gray-500">→</span> <span className="font-medium">{p.action}</span></PatientLine>)}
                      </ol>
                    </section>
                  )}
                  {s.by_ward.length > 0 && (
                    <section>
                      <h3 className="text-sm font-semibold text-gray-800 mb-1">By ward</h3>
                      <ul className="space-y-1">
                        {s.by_ward.map(w => <li key={w.ward} className="text-sm"><span className="font-medium">{w.ward}</span> <span className="text-xs text-gray-500">({w.count})</span> — {w.summary}</li>)}
                      </ul>
                    </section>
                  )}
                  {s.long_stay.length > 0 && (
                    <section>
                      <h3 className="text-sm font-semibold text-amber-700 mb-1">Long stay</h3>
                      <ul className="space-y-2">{s.long_stay.map(p => <PatientLine key={p.ref} p={p}>{p.note}</PatientLine>)}</ul>
                    </section>
                  )}
                  {s.discharge_candidates.length > 0 && (
                    <section>
                      <h3 className="text-sm font-semibold text-green-700 mb-1">Discharge review</h3>
                      <ul className="space-y-2">{s.discharge_candidates.map(p => <PatientLine key={p.ref} p={p}>{p.reason}</PatientLine>)}</ul>
                    </section>
                  )}
                  {s.data_gaps.length > 0 && (
                    <section>
                      <h3 className="text-sm font-semibold text-gray-700 mb-1">Documentation gaps</h3>
                      <ul className="list-disc pl-5 text-sm text-gray-700 space-y-0.5">{s.data_gaps.map((g, i) => <li key={i}>{g}</li>)}</ul>
                    </section>
                  )}
                  <p className="text-xs text-gray-500 flex items-start gap-1 border-t pt-2">
                    <ShieldCheck className="w-3.5 h-3.5 mt-0.5 shrink-0" />
                    Generated by Claude (Anthropic) from {result!.patient_count} de-identified records at {new Date(result!.generated_at).toLocaleTimeString()}.
                    Names and hospital numbers were removed before sending. Check against the patient before acting.
                  </p>
                </>
              )}
            </div>
          </div>
        </div>
      )}
    </>
  );
};

export default UnitAISummary;
