/** Small form controls shared by the nutrition screens. Every numeric field shows its unit. */
import React from 'react';

export const clean = (e: any) => String(e?.message || 'Something went wrong').replace(/^\[HTTP \d+\]\s*/, '');

export function Num({ label, unit, value, onChange, step = 'any' }: { label: string; unit?: string; value: any; onChange: (v: number | null) => void; step?: string }) {
  return (
    <label className="text-sm">
      <span className="text-gray-600">{label}{unit ? <span className="text-gray-400"> ({unit})</span> : null}</span>
      <input type="number" step={step} value={value ?? ''} onChange={e => onChange(e.target.value === '' ? null : Number(e.target.value))}
        className="mt-0.5 w-full border rounded px-2 py-1" />
    </label>
  );
}

export function Check({ label, value, onChange }: { label: string; value: any; onChange: (v: boolean) => void }) {
  return <label className="text-sm flex items-center gap-2"><input type="checkbox" checked={!!value} onChange={e => onChange(e.target.checked)} />{label}</label>;
}

export function Sel<T extends string>({ label, value, options, onChange }: { label: string; value: T | undefined | null; options: [T, string][]; onChange: (v: T | undefined) => void }) {
  return (
    <label className="text-sm">
      <span className="text-gray-600">{label}</span>
      <select value={value ?? ''} onChange={e => onChange((e.target.value || undefined) as T | undefined)} className="mt-0.5 w-full border rounded px-2 py-1 bg-white">
        <option value="">—</option>
        {options.map(([v, l]) => <option key={v} value={v}>{l}</option>)}
      </select>
    </label>
  );
}

export function Txt({ label, value, onChange, placeholder }: { label: string; value: any; onChange: (v: string) => void; placeholder?: string }) {
  return (
    <label className="text-sm">
      <span className="text-gray-600">{label}</span>
      <input value={value ?? ''} placeholder={placeholder} onChange={e => onChange(e.target.value)} className="mt-0.5 w-full border rounded px-2 py-1" />
    </label>
  );
}

export function Section({ title, children, hint }: { title: string; children: React.ReactNode; hint?: string }) {
  return (
    <fieldset className="border rounded-lg p-3">
      <legend className="px-1 text-sm font-medium text-gray-800">{title}</legend>
      {hint && <p className="text-xs text-gray-500 mb-2">{hint}</p>}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-3">{children}</div>
    </fieldset>
  );
}

export function StatusBadge({ status }: { status: string }) {
  const tone: Record<string, string> = {
    draft: 'bg-gray-100 text-gray-700', pending_review: 'bg-amber-100 text-amber-800', approved: 'bg-emerald-100 text-emerald-800',
    superseded: 'bg-gray-100 text-gray-500', entered_in_error: 'bg-red-100 text-red-700',
  };
  return <span className={`text-xs px-2 py-0.5 rounded-full ${tone[status] || 'bg-gray-100'}`}>{status.replace(/_/g, ' ')}</span>;
}

export const Notice = () => (
  <p className="text-xs text-gray-500 border-t pt-2 mt-2">Generated by decision-support software. Review before clinical use.</p>
);

export const levelTone = (l?: string | null) =>
  l === 'refeeding' ? 'bg-red-100 text-red-800' : l === 'high' ? 'bg-orange-100 text-orange-800' : l === 'medium' ? 'bg-amber-100 text-amber-800' : 'bg-emerald-100 text-emerald-800';
