/**
 * prepare-offline-assets.mjs
 *
 * Materialises every third-party asset the app would otherwise fetch from a CDN
 * at runtime into `public/`, so a built app has ZERO external network
 * dependencies and works on a ward with no connectivity.
 *
 * Runs before `vite build` (see package.json `prebuild`). Idempotent: files that
 * already exist are left alone, so repeat builds need no network.
 *
 *   public/fonts/       Inter webfont (was: fonts.googleapis.com @import)
 *   public/tesseract/   OCR worker + wasm core + English traineddata
 *                       (was: cdn.jsdelivr.net + tessdata.projectnaptha.com)
 */

import { createRequire } from 'node:module';
import { mkdir, copyFile, writeFile, readFile, access } from 'node:fs/promises';
import { constants } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(ROOT, 'public');

const FONTS_DIR = path.join(PUBLIC, 'fonts');
const TESS_DIR = path.join(PUBLIC, 'tesseract');

// Chrome UA — fonts.googleapis.com serves woff2 only to browsers that support it
const CHROME_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const exists = (p) => access(p, constants.F_OK).then(() => true, () => false);

async function download(url, dest, opts = {}) {
  if (await exists(dest)) {
    console.log(`  ✓ ${path.relative(ROOT, dest)} (cached)`);
    return;
  }
  const res = await fetch(url, { headers: opts.headers });
  if (!res.ok) throw new Error(`GET ${url} → HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(dest, buf);
  console.log(`  ↓ ${path.relative(ROOT, dest)} (${(buf.length / 1024).toFixed(0)} KB)`);
}

// ── Fonts ────────────────────────────────────────────────────────────
// The app's Tailwind `font-sans` is Inter. It used to arrive via an
// `@import url(fonts.googleapis.com…)` at the top of src/index.css — a
// render-blocking cross-origin request on every cold start, and a guaranteed
// miss on a device that has been offline since install.
const FONT_FAMILY = 'Inter:wght@300;400;500;600;700';
// Latin only. The clinical UI is English; pulling cyrillic/greek/vietnamese
// subsets would triple the payload for glyphs that never render.
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

async function prepareFonts() {
  console.log('▸ Inter webfont');
  await mkdir(FONTS_DIR, { recursive: true });

  const cssPath = path.join(FONTS_DIR, 'inter.css');
  if (await exists(cssPath)) {
    console.log('  ✓ public/fonts/inter.css (cached)');
    return;
  }

  const url = `https://fonts.googleapis.com/css2?family=${FONT_FAMILY}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': CHROME_UA } });
  if (!res.ok) throw new Error(`GET ${url} → HTTP ${res.status}`);
  const remoteCss = await res.text();

  // Google's CSS is a flat list of `/* subset */ @font-face { … }` blocks.
  // Keep the latin ones, download each woff2, and rewrite src → local path.
  const blocks = remoteCss.split('/*').filter((b) => b.includes('@font-face'));
  const kept = [];

  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf('*/')).trim();
    if (!KEEP_SUBSETS.has(subset)) continue;

    const weight = /font-weight:\s*(\d+)/.exec(block)?.[1] ?? '400';
    const remote = /src:\s*url\((https:\/\/[^)]+)\)/.exec(block)?.[1];
    if (!remote) continue;

    const file = `inter-${subset}-${weight}.woff2`;
    await download(remote, path.join(FONTS_DIR, file));

    kept.push(
      block
        .slice(block.indexOf('*/') + 2)
        .replace(/src:\s*url\(https:\/\/[^)]+\)/, `src: url(/fonts/${file})`)
        .trim()
    );
  }

  if (!kept.length) throw new Error('No latin @font-face blocks found in Google CSS');

  await writeFile(
    cssPath,
    `/* Self-hosted Inter — generated by scripts/prepare-offline-assets.mjs.\n` +
      `   Do not edit; delete the folder and re-run the script to refresh. */\n\n` +
      kept.join('\n\n') +
      '\n'
  );
  console.log(`  → public/fonts/inter.css (${kept.length} faces)`);
}

// ── Tesseract OCR ────────────────────────────────────────────────────
// tesseract.js fetches its worker, its wasm core and the language traineddata
// from jsdelivr/tessdata at *runtime*. Offline, OCR scanning simply failed.
//
// Only the LSTM cores are copied: ocrService creates its worker with
// OEM.LSTM_ONLY, so the legacy-engine cores would never be requested. The
// `relaxedsimd` variant is skipped deliberately — it is a pure speed
// optimisation over `simd`, and shipping it would add 3.8 MB that no device
// strictly needs (see pickTesseractCore in src/services/ocrService.ts).
const TESS_CORES = ['tesseract-core-simd-lstm.wasm.js', 'tesseract-core-lstm.wasm.js'];

// 4.0.0_fast: 2 MB vs 12 MB for `best`. Accuracy on printed clinical forms
// (lab reports, drug charts, vitals) is equivalent; `best` only pulls ahead on
// degraded scans, which the Cloud Vision path handles when online anyway.
const TRAINEDDATA_URL = 'https://tessdata.projectnaptha.com/4.0.0_fast/eng.traineddata.gz';

async function prepareTesseract() {
  console.log('▸ Tesseract OCR engine');
  await mkdir(TESS_DIR, { recursive: true });

  const workerSrc = require.resolve('tesseract.js/dist/worker.min.js');
  await copyFile(workerSrc, path.join(TESS_DIR, 'worker.min.js'));
  console.log('  → public/tesseract/worker.min.js');

  const coreDir = path.dirname(require.resolve('tesseract.js-core/package.json'));
  for (const core of TESS_CORES) {
    await copyFile(path.join(coreDir, core), path.join(TESS_DIR, core));
    console.log(`  → public/tesseract/${core}`);
  }

  await download(TRAINEDDATA_URL, path.join(TESS_DIR, 'eng.traineddata.gz'));

  // Record what the app should ask for, so the runtime warm-up list and the
  // shipped files can never drift apart.
  await writeFile(
    path.join(TESS_DIR, 'manifest.json'),
    JSON.stringify(
      {
        generatedBy: 'scripts/prepare-offline-assets.mjs',
        tesseractVersion: JSON.parse(
          await readFile(require.resolve('tesseract.js/package.json'), 'utf8')
        ).version,
        worker: '/tesseract/worker.min.js',
        cores: TESS_CORES.map((c) => `/tesseract/${c}`),
        lang: '/tesseract/eng.traineddata.gz',
      },
      null,
      2
    ) + '\n'
  );
  console.log('  → public/tesseract/manifest.json');
}

// ── Main ─────────────────────────────────────────────────────────────
try {
  await prepareFonts();
  await prepareTesseract();
  console.log('✅ Offline assets ready');
} catch (err) {
  // A missing font or traineddata must not break the build: the app degrades to
  // system fonts and to the online-only Cloud Vision OCR path. Fail loudly in
  // the log, exit 0.
  console.error(`⚠️  Offline asset preparation incomplete: ${err.message}`);
  console.error('   The build will continue; affected features fall back to online-only.');
  process.exit(0);
}
